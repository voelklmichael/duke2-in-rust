use dn2_engine::Key;
use winit::keyboard::KeyCode;

/// The engine's key for a physical key, if the game knows it.
pub fn translate(code: KeyCode) -> Option<Key> {
    use KeyCode::*;
    Some(match code {
        ArrowUp => Key::Up,
        ArrowDown => Key::Down,
        ArrowLeft => Key::Left,
        ArrowRight => Key::Right,
        Enter | NumpadEnter => Key::Enter,
        Escape => Key::Escape,
        Space => Key::Space,
        Backspace => Key::Backspace,
        Tab => Key::Tab,
        ControlLeft => Key::LeftCtrl,
        ControlRight => Key::RightCtrl,
        AltLeft => Key::LeftAlt,
        AltRight => Key::RightAlt,
        ShiftLeft => Key::LeftShift,
        ShiftRight => Key::RightShift,
        Insert => Key::Insert,
        Delete => Key::Delete,
        Home => Key::Home,
        End => Key::End,
        PageUp => Key::PageUp,
        PageDown => Key::PageDown,
        F1 => Key::F(1),
        F2 => Key::F(2),
        F3 => Key::F(3),
        F4 => Key::F(4),
        F5 => Key::F(5),
        F6 => Key::F(6),
        F7 => Key::F(7),
        F8 => Key::F(8),
        F9 => Key::F(9),
        F10 => Key::F(10),
        F11 => Key::F(11),
        F12 => Key::F(12),
        KeyA => Key::Letter('A'),
        KeyB => Key::Letter('B'),
        KeyC => Key::Letter('C'),
        KeyD => Key::Letter('D'),
        KeyE => Key::Letter('E'),
        KeyF => Key::Letter('F'),
        KeyG => Key::Letter('G'),
        KeyH => Key::Letter('H'),
        KeyI => Key::Letter('I'),
        KeyJ => Key::Letter('J'),
        KeyK => Key::Letter('K'),
        KeyL => Key::Letter('L'),
        KeyM => Key::Letter('M'),
        KeyN => Key::Letter('N'),
        KeyO => Key::Letter('O'),
        KeyP => Key::Letter('P'),
        KeyQ => Key::Letter('Q'),
        KeyR => Key::Letter('R'),
        KeyS => Key::Letter('S'),
        KeyT => Key::Letter('T'),
        KeyU => Key::Letter('U'),
        KeyV => Key::Letter('V'),
        KeyW => Key::Letter('W'),
        KeyX => Key::Letter('X'),
        KeyY => Key::Letter('Y'),
        KeyZ => Key::Letter('Z'),
        Digit0 => Key::Digit(0),
        Digit1 => Key::Digit(1),
        Digit2 => Key::Digit(2),
        Digit3 => Key::Digit(3),
        Digit4 => Key::Digit(4),
        Digit5 => Key::Digit(5),
        Digit6 => Key::Digit(6),
        Digit7 => Key::Digit(7),
        Digit8 => Key::Digit(8),
        Digit9 => Key::Digit(9),
        _ => return None,
    })
}
